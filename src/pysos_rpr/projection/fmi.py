@dataclass(frozen=True)
class _CodecField:
    signal: Signal
    chain: tuple[FieldDescriptor, ...]


def _walk_proto(names: tuple[str, ...]) -> tuple[FieldDescriptor, ...] | None:
    descriptor = entity_pb2.PhysicalEntity.DESCRIPTOR
    chain: list[FieldDescriptor] = []
    for index, name in enumerate(names):
        field = descriptor.fields_by_name.get(name)
        if field is None:
            return None
        chain.append(field)
        if index + 1 < len(names):
            if field.type != FieldDescriptor.TYPE_MESSAGE:
                return None
            descriptor = field.message_type
    leaf = chain[-1]
    if leaf.type == FieldDescriptor.TYPE_MESSAGE:
        return None
    if leaf.label == FieldDescriptor.LABEL_REPEATED:
        return None
    return tuple(chain)


def _resolve_path(path: str) -> tuple[FieldDescriptor, ...]:
    """Resolve a ``SCHEMA_PATHS`` value against ``PhysicalEntity``.

    Base-entity paths are stored without their ``base`` wrapper (the SysML
    generator flattens it), so both the bare path and the ``base``-prefixed
    path are tried.  Exactly one must exist.
    """

    parts = tuple(path.split("."))
    matches = [
        chain
        for chain in (_walk_proto(parts), _walk_proto(("base",) + parts))
        if chain is not None
    ]
    if len(matches) != 1:
        raise ValueError(
            f"schema path {path!r} resolves {len(matches)} times against "
            f"{ENTITY_MESSAGE}"
        )
    return matches[0]


def _flat_name(signal: Signal) -> str:
    if signal.name in SCHEMA_PATHS:
        return signal.name
    if "." in signal.name:
        tail = signal.name.rsplit(".", 1)[-1]
        if tail in SCHEMA_PATHS:
            return tail
    raise ProjectionError(
        "signal is not part of the rpr.v2.PhysicalEntity shape", signal_name=signal.name
    )


def _expected_type(field: FieldDescriptor) -> DataType:
    if field.type in (FieldDescriptor.TYPE_DOUBLE, FieldDescriptor.TYPE_FLOAT):
        return DataType.REAL
    if field.type in _INTEGER_PROTO_TYPES:
        return DataType.INTEGER
    if field.type == FieldDescriptor.TYPE_BOOL:
        return DataType.BOOLEAN
    if field.type == FieldDescriptor.TYPE_STRING:
        return DataType.STRING
    raise ProjectionError(
        f"protobuf type {field.type} has no FMI scalar",
        signal_name=field.full_name,
    )


def _codec_fields(model: ModelDefinition) -> tuple[_CodecField, ...]:
    resolved: list[_CodecField] = []
    seen: dict[str, str] = {}
    for signal in wire_signals(model):
        flat = _flat_name(signal)
        previous = seen.get(flat)
        if previous is not None and previous != signal.name:
            raise ProjectionError(
                f"signals {previous!r} and {signal.name!r} both map to {flat!r}",
                signal_name=signal.name,
            )
        seen[flat] = signal.name
        chain = _resolve_path(SCHEMA_PATHS[flat])
        expected = _expected_type(chain[-1])
        if signal.data_type is not expected:
            raise ProjectionError(
                f"declares {signal.data_type.value}, but {SCHEMA_PATHS[flat]} is "
                f"{PROTO_TYPES[flat]} ({expected.value})",
                signal_name=signal.name,
            )
        resolved.append(_CodecField(signal, chain))
    return tuple(resolved)


