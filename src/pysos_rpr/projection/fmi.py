_HEADER = "// Generated by pysos_rpr. Do not edit by hand.\n"

#: ``pysos_rpr`` is a source/editable layout here; a wheel does not carry the
#: proto tree, so the projection refuses to guess one.
_REPO_ROOT = Path(__file__).resolve().parents[3]
_PROTO_ROOT = _REPO_ROOT / "proto"

#: Frame representation.  Identity is a stand-in, not RPR conformance.
FRAME_MODES = ("identity", "exact")
FRAME_MODE = "identity"

_INTEGER_PROTO_TYPES = frozenset(
    {
        FieldDescriptor.TYPE_INT32,
        FieldDescriptor.TYPE_INT64,
        FieldDescriptor.TYPE_UINT32,
        FieldDescriptor.TYPE_UINT64,
        FieldDescriptor.TYPE_SINT32,
        FieldDescriptor.TYPE_SINT64,
        FieldDescriptor.TYPE_FIXED32,
        FieldDescriptor.TYPE_FIXED64,
        FieldDescriptor.TYPE_SFIXED32,
        FieldDescriptor.TYPE_SFIXED64,
        FieldDescriptor.TYPE_ENUM,
    }
)


_IMPORT = re.compile(r'^\s*import\s+"([^"]+)"', re.MULTILINE)


def _proto_files() -> tuple[Path, ...]:
    """Return every ``rpr.v2`` proto in import order.

    Imported files come before their importers so a parallel CMake build sees
    a generated header before it compiles a dependent ``.pb.cc``.  The order is
    read from the proto sources, never hand-written.
    """

    paths = sorted(_PROTO_ROOT.rglob("*.proto"))
    if not paths:
        raise FileNotFoundError(
            "rpr.v2 proto tree not found; the projection needs the source "
            f"checkout at {_PROTO_ROOT}"
        )
    by_relative = {path.relative_to(_PROTO_ROOT).as_posix(): path for path in paths}
    ordered: list[Path] = []
    seen: set[str] = set()

    def visit(relative: str) -> None:
        if relative in seen:
            return
        seen.add(relative)
        text = by_relative[relative].read_text(encoding="utf-8")
        for imported in _IMPORT.findall(text):
            if imported in by_relative:
                visit(imported)
        ordered.append(by_relative[relative])

    for relative in sorted(by_relative):
        visit(relative)
    return tuple(ordered)


def _projection_document(frame_mode: str) -> dict[str, Any]:
    return {
        "frame_mode": frame_mode,
        "entity_message": ENTITY_MESSAGE,
        "omitted_bytes": list(OMITTED_BYTES),
        "note": "identity mode is an interop stand-in, not RPR conformance",
    }


def _projection_json(frame_mode: str) -> bytes:
    return (json.dumps(_projection_document(frame_mode), indent=2) + "\n").encode("utf-8")


def resolve_frame_mode(value: str) -> str:
    """Return the frame mode this projection can honour, or raise.

    ``identity`` passes values through unconverted.  ``exact`` names the
    behaviour that would convert local ENU/body values to RPR's geocentric
    ECEF frames; it is reserved and refuses rather than approximating.
    """

    if value not in FRAME_MODES:
        raise ValueError(f"unknown frame_mode {value!r}; expected one of {FRAME_MODES}")
    if value == "exact":
        raise NotImplementedError(
            "frame_mode='exact' needs ENU/body/ECEF conversion and an origin; "
            "it is not implemented — use frame_mode='identity'"
        )
    return value


class RprSerialization(Serialization):
    """The FMI payload backend whose wire message is ``rpr.v2.PhysicalEntity``.

    ``format_id`` is ``1`` (protobuf), not a fresh uint16: the wire envelope's
    ``payload_format`` is a closed set (``0`` opaque, ``1`` protobuf, ``2``
    packed); both the C++ and Python decoders reject any other value.  The
    payload here *is* protobuf, so ``1`` is the only coherent tag.
    """

    name = "rpr"
    format_id = 1
    format_version = SCHEMA_FORMAT_VERSION
    frame_mode = FRAME_MODE

    def payload_message(self, model: ModelDefinition) -> str:
        return ENTITY_MESSAGE.rsplit(".", 1)[-1]

    def proto_package(self, model: ModelDefinition) -> str | None:
        return ENTITY_MESSAGE.rsplit(".", 1)[0]

    def schema_files(self, model: ModelDefinition) -> dict[str, bytes]:
        files = {str(path): path.read_bytes() for path in _proto_files()}
        files[WIRE_JSON_NAME] = wire_json_bytes(
            model, serialization=self.name, format_id=self.format_id
        )
        return files

    def cmake_proto_sources(self, model: ModelDefinition) -> tuple[str, ...]:
        # Reverse import order: a static archive that uses a type must precede
        # the archive that defines it on the linker line.
        return tuple(str(path) for path in reversed(_proto_files()))

    def cmake_proto_import_roots(self, model: ModelDefinition) -> tuple[str, ...]:
        return (str(_PROTO_ROOT),)

    def cmake_include_dirs(self, model: ModelDefinition) -> tuple[str, ...]:
        # The proto target propagates the generated include directory publicly.
        return ()

    def cmake_link_libraries(self, model: ModelDefinition) -> tuple[str, ...]:
        return ("protobuf::libprotobuf",)

    def generate_codec(
        self, model: ModelDefinition, out: str | Path, role: str
    ) -> list[Path]:
        fields = _codec_fields(model)
        return write_files(out, {"model_wire.cpp": _render_model_wire(model, fields)})


backend = RprSerialization()


def register() -> RprSerialization:
    """Register the ``rpr`` backend once; safe to call repeatedly.

    Importing this module intentionally registers nothing, so a consumer that
    only wanted the vocabulary never changes the serialization registry.
    """

    from pyfmi_interop.serialization import get
    from pyfmi_interop.serialization import register as register_backend

    try:
        existing = get(backend.name)
    except KeyError:
        return register_backend(backend)  # type: ignore[return-value]
    if not isinstance(existing, RprSerialization):
        raise ValueError(f"serialization backend {backend.name!r} is not the rpr projection")
    return existing


