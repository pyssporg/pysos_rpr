def _mutable_accessor(chain: tuple[FieldDescriptor, ...]) -> str:
    text = "message"
    separator = "."
    for field in chain[:-1]:
        text += f"{separator}mutable_{field.name}()"
        separator = "->"
    return text + f"{separator}set_{chain[-1].name}"


def _const_accessor(chain: tuple[FieldDescriptor, ...]) -> str:
    text = "message"
    for field in chain:
        text += f".{field.name}()"
    return text


def _enum_name(field: FieldDescriptor) -> str:
    return field.enum_type.full_name.replace(".", "::")


def _encode_value(field: FieldDescriptor, member: str) -> str:
    if field.type == FieldDescriptor.TYPE_DOUBLE:
        return member
    if field.type == FieldDescriptor.TYPE_FLOAT:
        return f"static_cast<float>({member})"
    if field.type == FieldDescriptor.TYPE_BOOL:
        return member
    if field.type == FieldDescriptor.TYPE_STRING:
        return f"std::string({member}.data(), bounded_length({member}))"
    if field.type == FieldDescriptor.TYPE_ENUM:
        return f"static_cast<{_enum_name(field)}>({member})"
    if field.type == FieldDescriptor.TYPE_INT32:
        return f"static_cast<std::int32_t>({member})"
    if field.type == FieldDescriptor.TYPE_INT64:
        return f"static_cast<std::int64_t>({member})"
    if field.type == FieldDescriptor.TYPE_UINT32:
        return f"static_cast<std::uint32_t>({member})"
    if field.type == FieldDescriptor.TYPE_UINT64:
        return f"static_cast<std::uint64_t>({member})"
    raise ProjectionError(
        f"protobuf type {field.type} has no generated setter", signal_name=field.full_name
    )


def _decode_statement(field: _CodecField) -> str:
    signal = field.signal
    member = member_name(signal)
    getter = _const_accessor(field.chain)
    leaf = field.chain[-1]
    if leaf.type == FieldDescriptor.TYPE_DOUBLE:
        return f"    {member} = {getter};"
    if leaf.type == FieldDescriptor.TYPE_FLOAT:
        return f"    {member} = static_cast<double>({getter});"
    if leaf.type == FieldDescriptor.TYPE_BOOL:
        return f"    {member} = {getter};"
    if leaf.type == FieldDescriptor.TYPE_STRING:
        return f"    copy_bounded({member}.data(), {member}.size(), {getter});"
    if leaf.type in (FieldDescriptor.TYPE_ENUM, FieldDescriptor.TYPE_INT32):
        return f"    {member} = static_cast<std::int32_t>({getter});"
    if leaf.type == FieldDescriptor.TYPE_INT64:
        return f"    {member} = static_cast<std::int64_t>({getter});"
    if leaf.type == FieldDescriptor.TYPE_UINT32:
        return f"    {member} = static_cast<std::int32_t>({getter});"
    if leaf.type == FieldDescriptor.TYPE_UINT64:
        return f"    {member} = static_cast<std::int64_t>({getter});"
    raise ProjectionError(
        f"protobuf type {leaf.type} has no generated getter", signal_name=signal.name
    )


def _encode_statement(field: _CodecField) -> str:
    leaf = field.chain[-1]
    value = _encode_value(leaf, member_name(field.signal))
    return f"    {_mutable_accessor(field.chain)}({value});"


def _render_model_wire(model: ModelDefinition, fields: tuple[_CodecField, ...]) -> str:
    encode_lines = "\n".join(_encode_statement(field) for field in fields)
    decode_lines = "\n".join(_decode_statement(field) for field in fields)
    if not encode_lines:
        encode_lines = "    (void)message;"
    if not decode_lines:
        decode_lines = "    (void)message;"
    records = ", ".join(
        f"{{{signal.value_reference}u, {signal.data_type.number}u}}"
        for signal in wire_signals(model)
    )
    message = "rpr::v2::PhysicalEntity"
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + f"// IR fingerprint: {fingerprint(model)}\n"
        + "//\n"
        + "// Payload layer for the rpr.v2.PhysicalEntity wire contract.  Every field\n"
        + "// is written through the generated protobuf accessors; no protobuf byte\n"
        + "// layout is written by hand and identity mode performs no frame maths.\n"
        + '#include "model_runtime.hpp"\n'
        + "\n"
        + '#include "rpr/v2/entity.pb.h"\n'
        + '#include "pyfmi_interop/runtime/wire.hpp"\n'
        + "\n"
        + "#include <array>\n"
        + "#include <cstddef>\n"
        + "#include <cstdint>\n"
        + "#include <limits>\n"
        + "#include <string>\n"
        + "#include <string_view>\n"
        + "#include <vector>\n"
        + "\n"
        + "namespace {\n"
        + "\n"
        + f"constexpr char kModelName[] = {string_literal(model.name)};\n"
        + "\n"
        + "template <std::size_t N>\n"
        + "std::size_t bounded_length(const std::array<char, N>& value) {\n"
        + "    std::size_t length = 0;\n"
        + "    while (length < N && value[length] != '\\0') {\n"
        + "        ++length;\n"
        + "    }\n"
        + "    return length;\n"
        + "}\n"
        + "\n"
        + "const std::array<std::uint8_t, pyfmi_interop::wire::kModelIdSize>& "
        + "wire_model_id() {\n"
        + "    static const std::array<std::uint8_t, pyfmi_interop::wire::kModelIdSize> id =\n"
        + "        pyfmi_interop::wire::model_id(\n"
        + "            std::string_view(kModelName),\n"
        + "            std::vector<pyfmi_interop::wire::ModelIdSignal>{" + records + "});\n"
        + "    return id;\n"
        + "}\n"
        + "\n"
        + "}  // namespace\n"
        + "\n"
        + "bool GeneratedModelRuntime::encode_wire_payload(std::string& payload,\n"
        + "                                                std::string& error) const {\n"
        + f"    {message} message;\n"
        + encode_lines
        + "\n"
        + "    payload = message.SerializeAsString();\n"
        + "    if (payload.size() > std::numeric_limits<std::uint32_t>::max()) {\n"
        + '        error = "payload exceeds uint32 length";\n'
        + "        return false;\n"
        + "    }\n"
        + "    return true;\n"
        + "}\n"
        + "\n"
        + "bool GeneratedModelRuntime::decode_wire_payload(std::string_view payload,\n"
        + "                                                std::string& error) {\n"
        + f"    {message} message;\n"
        + "    if (payload.size() >\n"
        + "        static_cast<std::size_t>(std::numeric_limits<int>::max())) {\n"
        + '        error = "payload is too large to parse";\n'
        + "        return false;\n"
        + "    }\n"
        + "    if (!message.ParseFromArray(payload.data(), static_cast<int>(payload.size()))) {\n"
        + '        error = "payload is not a valid rpr.v2.PhysicalEntity message";\n'
        + "        return false;\n"
        + "    }\n"
        + decode_lines
        + "\n"
        + "    return true;\n"
        + "}\n"
        + "\n"
        + "std::vector<std::uint8_t> GeneratedModelRuntime::encode_wire_frame(\n"
        + "    std::uint32_t instance, std::uint64_t sequence, std::uint64_t timestamp_ns,\n"
        + "    std::string& error) const {\n"
        + "    error.clear();\n"
        + "    std::string payload;\n"
        + "    if (!encode_wire_payload(payload, error)) {\n"
        + "        return {};\n"
        + "    }\n"
        + "    pyfmi_interop::wire::EncodeResult result = pyfmi_interop::wire::encode_frame(\n"
        + "        wire_model_id(), payload, instance, sequence, timestamp_ns,\n"
        + "        pyfmi_interop::wire::PayloadFormat::Protobuf);\n"
        + "    if (!result) {\n"
        + "        error = result.error.message;\n"
        + "        return {};\n"
        + "    }\n"
        + "    return std::move(result.frame);\n"
        + "}\n"
        + "\n"
        + "bool GeneratedModelRuntime::decode_wire_frame(\n"
        + "    const std::vector<std::uint8_t>& frame, std::string& error) {\n"
        + "    error.clear();\n"
        + "    const std::string_view buffer(\n"
        + "        reinterpret_cast<const char*>(frame.data()), frame.size());\n"
        + "    pyfmi_interop::wire::DecodeResult result =\n"
        + "        pyfmi_interop::wire::decode_frame(buffer);\n"
        + "    if (!result) {\n"
        + "        error = result.error.message;\n"
        + "        return false;\n"
        + "    }\n"
        + "    if (result.frame.header.model_id != wire_model_id()) {\n"
        + '        error = "model id mismatch";\n'
        + "        return false;\n"
        + "    }\n"
        + "    if (result.frame.header.payload_format !=\n"
        + "        pyfmi_interop::wire::PayloadFormat::Protobuf) {\n"
        + '        error = "payload format mismatch";\n'
        + "        return false;\n"
        + "    }\n"
        + "    const std::string_view payload(\n"
        + "        reinterpret_cast<const char*>(result.frame.payload.data()),\n"
        + "        result.frame.payload.size());\n"
        + "    return decode_wire_payload(payload, error);\n"
        + "}\n"
    )


